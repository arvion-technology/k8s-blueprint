#!/usr/bin/env node
// Render the chart with its default values into base/ so the Kustomize overlays
// have a plain-manifest base. Run after changing chart templates or values:
//
//   node scripts/render-base.mjs
//
// test/chart.test.js fails when base/ is older than the chart render.

import { writeFileSync, mkdirSync, readFileSync } from "node:fs";
import { join, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import { renderChart } from "../src/render.js";
import { loadChart } from "./chart-files.mjs";

const root = resolve(fileURLToPath(new URL("..", import.meta.url)));
const { chart } = loadChart(root);
const rendered = renderChart({ chart });
const baseDir = join(root, "base");
mkdirSync(baseDir, { recursive: true });

const resources = [];
for (const file of rendered) {
  if (file.path.startsWith("tests/")) continue;
  const name = file.path.split("/").pop();
  writeFileSync(join(baseDir, name), file.content, "utf8");
  resources.push(name);
}
writeFileSync(join(baseDir, "kustomization.yaml"), `apiVersion: kustomize.config.k8s.io/v1beta1
kind: Kustomization
# Generated by scripts/render-base.mjs from chart/ with default values.
# Overlays in ../overlays add a namespace and JSON patches on top of this.
resources:
${resources.sort().map((name) => `  - ${name}`).join("\n")}
`, "utf8");
console.log(`rendered ${resources.length} manifests into base/`);

#!/usr/bin/env node
// Regenerate demo/chart-data.js from chart/ and overlays/.
//
//   node scripts/sync-demo.mjs
//
// The manifest explorer imports this data and renders it with src/render.js in
// the browser, so the demo cannot drift from the chart without test/chart.test.js
// failing.

import { writeFileSync } from "node:fs";
import { join, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import { loadChart, loadOverlays } from "./chart-files.mjs";

const root = resolve(fileURLToPath(new URL("..", import.meta.url)));
const { chart } = loadChart(root);
const overlays = loadOverlays(root);

const body = `// Generated by scripts/sync-demo.mjs from chart/ and overlays/.
// Do not edit by hand; run \`npm run sync\` after changing the chart.

export const CHART = ${JSON.stringify(chart, null, 2)};

export const OVERLAYS = ${JSON.stringify(overlays, null, 2)};
`;
writeFileSync(join(root, "demo/chart-data.js"), body, "utf8");
console.log(`wrote demo/chart-data.js (${overlays.length} overlays, ${Object.keys(chart.templates).length} templates)`);
